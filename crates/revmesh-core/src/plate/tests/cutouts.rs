use std::f64::consts::PI;

use crate::plate::P2;
use crate::recognize::{ArcSide, CutoutSpec};
use crate::synth;

use super::{found_profile, plate_with_cutout, reason, spec, stadium};

/// A D-shaped cut-out (half a circle closed by its diameter) has every corner on a circle;
/// it must not become a round hole.
#[test]
fn d_shaped_cut_out_is_not_a_hole() {
    let outline = [[0.0, 0.0], [80.0, 0.0], [80.0, 50.0], [0.0, 50.0]];
    let half: Vec<P2> = (0..=32).map(|i| f64::from(i) * PI / 32.0).map(|a| [40.0 + 2.0 * a.cos(), 25.0 + 2.0 * a.sin()]).collect();
    assert!(reason(&synth::prism(&outline, &[half], 5.0, [0.0; 3])).contains("not round"));
    // A shaft's D-hole: a full circle with a flat cutting off a 74° arc.
    let flat = (0.8_f64).acos();
    let mut shaft: Vec<P2> = (0..=27)
        .map(|i| -PI + flat + f64::from(i) * (2.0 * PI - 2.0 * flat) / 27.0)
        .map(|a| [40.0 + 2.5 * a.cos(), 25.0 + 2.5 * a.sin()])
        .collect();
    shaft.rotate_left(14);
    assert!(reason(&synth::prism(&outline, &[shaft], 5.0, [0.0; 3])).contains("not round"));
}

/// A hole of six facets is no round hole but a hexagonal cut-out, rebuilt as it is.
#[test]
fn hexagonal_cut_out_is_not_a_hole() {
    let (plate, _) = found_profile(&synth::plate(&spec(&[(40.0, 25.0, 10.0)], None), 6, [0.0; 3]));
    assert_eq!(plate.holes, []);
    assert_eq!(plate.cutouts.len(), 1);
    assert_eq!(plate.cutouts[0].corners.len(), 6);
    assert_eq!(plate.cutouts[0].corners[0], [37.5, 20.67]);
}

/// A 70 x 40 x 6 plate exported from SolidCraft 0.50 with a 16 x 20 rectangular and a
/// hexagonal cut-out (7 mm to its corners) and an Ø5 hole.
#[test]
fn recognises_polygonal_cut_outs() {
    let mesh = crate::stl::parse(include_bytes!("../../../../../plugin/revmesh/tests/cutouts.stl")).expect("parses");
    let (plate, _) = found_profile(&mesh);
    assert_eq!(plate.corners, [[0.0, 0.0], [70.0, 0.0], [70.0, 40.0], [0.0, 40.0]]);
    assert_eq!(plate.cutouts.len(), 2);
    assert_eq!(plate.cutouts[0].corners, [[8.0, 10.0], [24.0, 10.0], [24.0, 30.0], [8.0, 30.0]]);
    assert_eq!(plate.cutouts[1].corners.len(), 6);
    // SolidCraft measured 13,998.356 mm³; the hexagon's corners are rounded to 0.01 mm.
    assert!((plate.volume() - 13_998.356).abs() < 0.05, "{}", plate.volume());
}

/// Cut-outs of straight sides: a rectangle, a triangle, an L-shape, and a slot whose ends
/// are three facets each. A curve of many gentle corners is no polygon.
#[test]
fn polygonal_cut_outs() {
    let rectangle = vec![[10.0, 10.0], [25.0, 10.0], [25.0, 30.0], [10.0, 30.0]];
    let triangle = vec![[40.0, 10.0], [60.0, 12.0], [48.0, 30.0]];
    let ell = vec![[30.0, 35.0], [50.0, 35.0], [50.0, 40.0], [35.0, 40.0], [35.0, 45.0], [30.0, 45.0]];
    let outline = [[0.0, 0.0], [80.0, 0.0], [80.0, 50.0], [0.0, 50.0]];
    let mesh = synth::prism(&outline, &[rectangle.clone(), triangle.clone(), ell.clone()], 6.0, [0.0; 3]);
    let (plate, _) = found_profile(&mesh);
    let corners: Vec<Vec<P2>> = plate.cutouts.iter().map(|c| c.corners.clone()).collect();
    assert_eq!(corners, [rectangle, triangle, ell]);
    assert!(plate.cutouts.iter().all(|c| !c.has_arcs()));
    assert!((plate.volume() - mesh.volume()).abs() < 1e-6);
    let (plate, _) = found_profile(&plate_with_cutout(stadium([40.0, 25.0], 18.0, 7.0, 0.0, 3)));
    assert_eq!(plate.cutouts[0].corners.len(), 8);
    let gentle: Vec<P2> = (0..30).map(|i| 2.0 * PI * f64::from(i) / 30.0).map(|a| [40.0 + 12.0 * a.cos(), 25.0 + 6.0 * a.sin()]).collect();
    reason(&plate_with_cutout(gentle));
}

/// `cutout-arc.stl` (generated by the `plate_stl` example): a 70 x 40 x 6 plate with a 16 x 16
/// cut-out whose top side is a radius-8 semicircle. Recognised with the arc side on side 3 and
/// the deviation report measuring it as `cut-out 1, arc side 3`.
#[test]
fn recognises_the_arc_sided_cut_out_fixture() {
    let mesh = crate::stl::parse(include_bytes!("../../../../../plugin/revmesh/tests/cutout-arc.stl")).expect("parses");
    let (plate, _) = found_profile(&mesh);
    assert_eq!(plate.cutouts.len(), 1);
    let c = &plate.cutouts[0];
    assert_eq!(c.corners, [[10.0, 10.0], [26.0, 10.0], [26.0, 26.0], [10.0, 26.0]]);
    let arc = c.arcs[2].expect("the top side is an arc side");
    assert_eq!(arc.centre, [18.0, 26.0]);
    assert!((arc.r - 8.0).abs() < 1e-9, "{}", arc.r);
    assert!((plate.volume() - 14_660.814_211).abs() < 0.01, "{}", plate.volume());
    let deviations = crate::plate::face_deviations(&mesh);
    let arc_side = deviations.iter().find(|(label, _)| label.contains("arc side")).expect("the arc side is reported");
    assert!(arc_side.0.contains("cut-out 1, arc side 3"), "{}", arc_side.0);
    assert!(arc_side.1 < 0.01, "the facets' sagitta, in mm: {}", arc_side.1);
}

/// A cut-out with an arc side — a 20 x 20 square whose top side bulges out as a radius-10
/// semicircle — is recognised as a cut-out with an arc side on its third side, and the rebuilt
/// profile matches the mesh's volume.
#[test]
fn arc_sided_cut_out_is_recognised() {
    let corners: Vec<P2> = vec![[10.0, 10.0], [30.0, 10.0], [30.0, 30.0], [10.0, 30.0]];
    let arcs: Vec<Option<ArcSide>> = vec![None, None, Some(ArcSide { centre: [20.0, 30.0], r: 10.0 }), None];
    let mesh = plate_with_cutout(synth::faceted_polygon(&corners, &arcs, 8));
    let (plate, _) = found_profile(&mesh);
    assert_eq!(plate.cutouts.len(), 1);
    let c: &CutoutSpec = &plate.cutouts[0];
    assert_eq!(c.corners, corners);
    assert!(c.arcs.iter().enumerate().all(|(i, a)| i == 2 || a.is_none()), "only the third side is an arc: {:?}", c.arcs);
    let arc = c.arcs[2].expect("the top side is an arc side");
    assert_eq!(arc.centre, [20.0, 30.0]);
    assert!((arc.r - 10.0).abs() < 1e-9, "the fitted radius, snapped: {}", arc.r);
    assert!((plate.volume() - mesh.volume()).abs() / mesh.volume() < 0.01, "{} vs {}", plate.volume(), mesh.volume());
}

/// A cut-out whose corners are all rounded stays a mesh: its rounds would need a fillet on the
/// cut-out's vertical edges, which is not recognised yet.
#[test]
fn rounded_corner_cut_out_stays_a_mesh() {
    let ring = synth::rounded(&[[10.0, 10.0], [30.0, 10.0], [30.0, 30.0], [10.0, 30.0]], Some(3.0), 32);
    reason(&plate_with_cutout(ring));
}

/// A concave arc side in a cut-out (a notch bowing into the opening) is refused, as in outlines:
/// the sketch arcs are counter-clockwise, so emitting it would rebuild the complementary bulge.
#[test]
fn concave_arc_cut_out_is_refused() {
    // A 20 x 20 square whose top side is an arc about [20, 40] (in the material) bulging down
    // into the opening: a clockwise (concave) sweep in the counter-clockwise loop.
    let r = (200.0_f64).sqrt();
    let mut ring: Vec<P2> = vec![[10.0, 10.0], [30.0, 10.0], [30.0, 30.0]];
    for k in 1..16 {
        let t = -PI / 4.0 - (PI / 2.0) * f64::from(k) / 16.0; // clockwise from -45 deg to -135 deg
        ring.push([20.0 + r * t.cos(), 40.0 + r * t.sin()]);
    }
    ring.push([10.0, 30.0]);
    reason(&plate_with_cutout(ring));
}
